#!/usr/bin/env python3
"""User-level code installation. Never import, rewrite or delete connection state."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import shlex
import subprocess
import sys
import tempfile
import time


CONSOLE_MODULES = (
    'bindkit_console.py', 'bindkit_policy.py', 'bindkit_vault.py',
    'bindkit_privilege.py', 'bindkit_connections.py', 'bindkit_ai.py',
    'bindkit_catalog.py', 'bindkit_imports.py', 'bindkit_admin.py',
    'bindkit_orchestration.py', 'bindkit_xshell_crypto.py', 'bindkit_pending.py',
    'bindkit_password.py', 'bindkit_askpass.py',
)


def build_integrations_runtime(runtime, requirements):
    """Build only inside a new private venv; never import/use a real vault."""
    runtime, requirements = Path(runtime), Path(requirements)
    environment = {key: value for key, value in os.environ.items()
                   if not key.startswith(('PIP_', 'PYTHON'))}
    try:
        subprocess.run([sys.executable, '-m', 'venv', str(runtime)], check=True,
                       env=environment, capture_output=True, timeout=120)
        interpreter = runtime / 'bin/python'
        subprocess.run([str(interpreter), '-I', '-m', 'pip', '--isolated', 'install',
                        '--require-virtualenv', '--prefix', str(runtime), '--no-user',
                        '--disable-pip-version-check', '--no-input', '--timeout', '20',
                        '--retries', '1', '-r', str(requirements)],
                       check=True, env=environment, capture_output=True, timeout=300)
        # Import checks do not select or access an OS keychain backend.
        subprocess.run([str(interpreter), '-I', '-c', 'import keyring, openai; from Crypto.Cipher import ARC4'],
                       check=True, env=environment, capture_output=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        raise RuntimeError('Optional integration runtime setup failed. Check Python venv/pip support and access to PyPI, then retry --with-integrations. Existing installation was preserved.') from None


def _runtime_from_receipt(prior, data_dir):
    metadata = prior.get('integrations')
    if not metadata:
        return None
    if not isinstance(metadata, dict) or not isinstance(metadata.get('path'), str):
        raise RuntimeError('Invalid integration runtime receipt; existing installation was preserved')
    runtime = Path(metadata['path'])
    if runtime.parent != data_dir or not runtime.name.startswith('integrations-runtime-') or runtime.is_symlink():
        raise RuntimeError('Unsafe integration runtime path; existing installation was preserved')
    return runtime


def _launcher(interpreter, command, console_dir):
    return ('#!/bin/sh\n'
            '# BindKit optional integration runtime. Generated by the installer.\n'
            'if [ -z "${BINDCONSOLE_HOME:-}" ]; then\n'
            '  BINDCONSOLE_HOME=' + shlex.quote(str(console_dir)) + '\n'
            '  export BINDCONSOLE_HOME\n'
            'fi\n'
            'exec ' + shlex.quote(str(interpreter)) + ' ' + shlex.quote(str(command)) + ' "$@"\n').encode()


def atomic_write(path, content, mode):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, tmp = tempfile.mkstemp(prefix='.bindkit-install-', dir=str(path.parent))
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def write_file(path, content, mode):
    atomic_write(path, content, mode)


def install(source, home, bin_dir=None, console_dir=None, data_dir=None,
            with_integrations=False, runtime_builder=None):
    source, home = Path(source).resolve(), Path(home).resolve()
    if os.name != 'posix' or sys.version_info < (3, 9):
        raise RuntimeError('BindKit requires macOS/Linux and Python 3.9 or later')
    if not shutil.which('ssh') or not shutil.which('ssh-keygen'):
        raise RuntimeError('OpenSSH client and ssh-keygen are required')
    bin_dir = Path(bin_dir).expanduser().absolute() if bin_dir else home / '.local/bin'
    console_dir = Path(console_dir).expanduser().absolute() if console_dir else home / '.bindconsole'
    data_dir = Path(data_dir).expanduser().absolute() if data_dir else home / '.local/share/bindkit'
    version = (source / 'VERSION').read_text().strip()
    receipt_path = data_dir / 'install-receipt.json'
    try:
        prior = json.loads(receipt_path.read_text())
        prior_hashes = {x['path']: x['sha256'] for x in prior['files']}
    except (OSError, ValueError, KeyError, TypeError):
        prior = {}
        prior_hashes = {}
    prior_runtime = _runtime_from_receipt(prior, data_dir)
    enabled = bool(with_integrations or prior_runtime)
    command_dir = data_dir / 'commands' if enabled else bin_dir
    mapping = [(source / 'sshbind/sshbind', command_dir / 'sshbind', 0o755),
               (source / 'dbbind/dbbind', command_dir / 'dbbind', 0o755)]
    for name in CONSOLE_MODULES:
        mapping.append((source / 'bindconsole' / name, console_dir / 'lib' / name, 0o644))
    for name in ('index.html', 'style.css', 'api.js', 'ui.js', 'app.js', 'pages.js'):
        mapping.append((source / 'bindconsole/web' / name, console_dir / 'web' / name, 0o644))
    for name in ('VERSION', 'README.md', 'LICENSE', 'AGENT.md', 'requirements-integrations.txt'):
        mapping.append((source / name, data_dir / name, 0o644))
    mapping.append((source / 'scripts/uninstall.py', data_dir / 'uninstall.py', 0o755))
    # Update only our unmodified managed guides; handwritten/edited guides belong to the user.
    for relative in ('.dbbind/AGENT.md', '.ssh/sshbind/AGENT.md'):
        dest = home / relative
        if not os.path.lexists(dest) or (str(dest) in prior_hashes and not dest.is_symlink()
                                       and dest.is_file()
                                       and hashlib.sha256(dest.read_bytes()).hexdigest() == prior_hashes[str(dest)]):
            mapping.append((source / 'AGENT.md', dest, 0o644))
    updates = []
    receipt_files = []
    for src, dest, mode in mapping:
        if src.is_symlink() or not src.is_file():
            raise RuntimeError('Missing or unsafe installation source: %s' % src.name)
        if dest.is_dir() and not dest.is_symlink():
            raise RuntimeError('Refusing to replace directory: %s' % dest)
        content = src.read_bytes()
        receipt_files.append({'path': str(dest), 'sha256': hashlib.sha256(content).hexdigest()})
        updates.append((dest, content, mode))
    runtime = None
    new_runtime = None
    runtime_metadata = None
    if enabled:
        requirements = source / 'requirements-integrations.txt'
        digest = hashlib.sha256(requirements.read_bytes()).hexdigest()
        prior_metadata = prior.get('integrations') or {}
        reusable = (prior_runtime is not None and prior_runtime.is_dir()
                    and (prior_runtime / 'bin/python').is_file()
                    and os.access(prior_runtime / 'bin/python', os.X_OK)
                    and (prior_runtime / '.bindkit-runtime.json').is_file())
        if reusable and prior_metadata.get('requirements_sha256') == digest:
            runtime, runtime_metadata = prior_runtime, prior_metadata
        elif not with_integrations and not reusable:
            raise RuntimeError('Previously enabled integration runtime is missing or damaged; rerun with --with-integrations. Existing installation was preserved.')
        else:
            data_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
            runtime = new_runtime = Path(tempfile.mkdtemp(prefix='integrations-runtime-', dir=str(data_dir)))
            try:
                (runtime_builder or build_integrations_runtime)(runtime, requirements)
                if not (runtime / 'bin/python').is_file() or not os.access(runtime / 'bin/python', os.X_OK):
                    raise RuntimeError('Optional integration runtime did not provide an executable Python')
                runtime_metadata = {'path': str(runtime), 'requirements_sha256': digest,
                                    'python_version': list(sys.version_info[:2])}
                atomic_write(runtime / '.bindkit-runtime.json', json.dumps(runtime_metadata).encode(), 0o600)
            except BaseException:
                shutil.rmtree(new_runtime)
                raise
        for tool in ('sshbind', 'dbbind'):
            dest = bin_dir / tool
            if dest.is_dir() and not dest.is_symlink():
                if new_runtime: shutil.rmtree(new_runtime)
                raise RuntimeError('Refusing to replace directory: %s' % dest)
            content = _launcher(runtime / 'bin/python', command_dir / tool, console_dir)
            receipt_files.append({'path': str(dest), 'sha256': hashlib.sha256(content).hexdigest()})
            updates.append((dest, content, 0o755))
    receipt = json.dumps({'version': version, 'files': receipt_files,
                          'integrations': runtime_metadata}, indent=2).encode() + b'\n'
    updates.append((receipt_path, receipt, 0o600))
    changed, backups = [], []
    try:
        for dest, content, mode in updates:
            previous = None
            backup = None
            if os.path.lexists(dest):
                if dest.is_symlink():
                    previous = ('link', os.readlink(dest), None)
                else:
                    previous = ('file', dest.read_bytes(), dest.stat().st_mode & 0o777)
                if previous[0] == 'file' and previous[1] == content and previous[2] == mode:
                    continue
                backup = dest.with_name(dest.name + '.bindkit-backup-' + str(time.time_ns()))
                backups.append(backup)
                shutil.copy2(dest, backup, follow_symlinks=False)
            changed.append((dest, backup))
            write_file(dest, content, mode)
    except BaseException:
        failed_restores = set()
        for dest, backup in reversed(changed):
            try:
                if backup is None:
                    if os.path.lexists(dest):
                        dest.unlink()
                else:
                    # Rename the existing backup: rollback must still work when the
                    # filesystem has no space for a newly allocated replacement.
                    os.replace(backup, dest)
            except OSError:
                if backup is not None:
                    failed_restores.add(backup)
                print('Rollback needs manual recovery for %s' % dest, file=sys.stderr)
        for backup in backups:
            if backup not in failed_restores and os.path.lexists(backup):
                backup.unlink()
        if new_runtime:
            shutil.rmtree(new_runtime)
        raise
    return {'version': version, 'bin_dir': str(bin_dir), 'console_dir': str(console_dir),
            'data_dir': str(data_dir), 'integrations': enabled,
            'runtime': str(runtime) if runtime else None, 'backups': [str(p) for p in backups]}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source-dir', type=Path, default=Path(__file__).resolve().parents[1])
    p.add_argument('--bin-dir', type=Path)
    p.add_argument('--console-dir', type=Path)
    p.add_argument('--data-dir', type=Path)
    p.add_argument('--with-integrations', action='store_true',
                   help='Install optional keyring/model SDK into an isolated private virtualenv')
    args = p.parse_args()
    try:
        result = install(args.source_dir, Path.home(), args.bin_dir,
                         args.console_dir or os.environ.get('BINDCONSOLE_HOME'), args.data_dir,
                         with_integrations=args.with_integrations)
    except (OSError, RuntimeError, ValueError) as exc:
        p.exit(1, 'Installation failed: %s\n' % exc)
    print('BindKit %s installed in %s' % (result['version'], result['bin_dir']))
    if result['bin_dir'] not in os.environ.get('PATH', '').split(os.pathsep):
        import shlex
        print('Add to your shell: export PATH=%s:"$PATH"' % shlex.quote(result['bin_dir']))
    if result['integrations']:
        print('Optional integration runtime: %s' % result['runtime'])
    print('Start: sshbind --startserver  /  dbbind --startserver')
    print('Existing connections, credentials, policies and approvals were preserved.')
    if result['backups']:
        print('Previous code backed up beside replaced files (%d files).' % len(result['backups']))


if __name__ == '__main__':
    main()
